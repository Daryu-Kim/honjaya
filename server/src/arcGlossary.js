function termSpans(line, needle) {
  const lowerLine = line.toLowerCase();
  const lowerNeedle = needle.toLowerCase();
  const spans = [];

  if (/^[a-z0-9 ]+$/i.test(needle)) {
    // 영문·숫자 용어는 단어 경계로 찾습니다(예: 'RN'이 다른 단어 안에서 잡히지 않게).
    const pattern = new RegExp(
      `(?<![a-z0-9])${lowerNeedle.replaceAll(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?![a-z0-9])`,
      "g"
    );
    let match = pattern.exec(lowerLine);

    while (match !== null) {
      spans.push([match.index, match.index + lowerNeedle.length]);
      match = pattern.exec(lowerLine);
    }

    return spans;
  }

  let from = 0;

  while (from <= lowerLine.length) {
    const index = lowerLine.indexOf(lowerNeedle, from);

    if (index < 0) break;

    spans.push([index, index + lowerNeedle.length]);
    from = index + 1;
  }

  return spans;
}

/**
 * 문장 목록에서 실제로 등장한 어려운 말만 골라 돌려줍니다.
 * 긴 용어를 먼저 찾아 "감염노출"과 "감염"이 겹쳐 잡히지 않게 합니다.
 */
export function collectArcTerms(texts = []) {
  const found = new Map();

  for (const raw of Array.isArray(texts) ? texts : [texts]) {
    const line = String(raw ?? "");

    if (!line) continue;

    const used = [];

    for (const entry of ARC_GLOSSARY) {
      if (found.has(entry.term)) continue;

      const needles = [entry.term, ...(entry.aliases ?? [])];
      let hit = false;

      for (const needle of needles) {
        const free = termSpans(line, needle).find(([start, stop]) =>
          used.every(([takenStart, takenStop]) => stop <= takenStart || takenStop <= start)
        );

        if (free) {
          used.push(free);
          hit = true;
          break;
        }
      }

      if (hit) {
        found.set(entry.term, { term: entry.term, plain: entry.plain });
      }
    }
  }

  return [...found.values()];
}
